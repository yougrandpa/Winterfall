        public static Sprite Get(string key)
        {
            Sprite sprite;
            if (Cache.TryGetValue(key, out sprite))
            {
                return sprite;
            }

            string[] rows;
            if (!Masks.TryGetValue(key, out rows))
            {
                return null;
            }

            sprite = Build(rows);
            Cache[key] = sprite;
            return sprite;
        }

        private static Sprite Build(string[] rows)
        {
            int height = rows.Length;
            int width = rows[0].Length;
            var texture = new Texture2D(width, height, TextureFormat.RGBA32, false);
            texture.name = "HudIcon";
            texture.hideFlags = HideFlags.HideAndDontSave;
            texture.wrapMode = TextureWrapMode.Clamp;
            texture.filterMode = FilterMode.Point;
            Color32 on = new Color32(255, 255, 255, 255);
            Color32 off = new Color32(255, 255, 255, 0);
            for (int y = 0; y < height; y++)
            {
                string row = rows[y];
                for (int x = 0; x < width; x++)
                {
                    texture.SetPixel(x, height - 1 - y, x < row.Length && row[x] == '#' ? (Color)on : (Color)off);
                }
            }

            texture.Apply();
            var sprite = Sprite.Create(texture, new Rect(0, 0, width, height), Vector2.one * 0.5f, 100f, 0,
                SpriteMeshType.FullRect);
            sprite.name = "hud_icon";
            sprite.hideFlags = HideFlags.HideAndDontSave;
            return sprite;
        }
